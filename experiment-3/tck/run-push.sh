#!/usr/bin/env bash
# Runs the TCK MUST level with push notifications switched on (A2A_PUSH_ENABLED=true), the way the client agent
# needs the server, and judges it with tck/check_results.py --push: every PUSH-* requirement must PASS. With the
# capability declared the TCK skips CORE-CAP-001 (error when push is unsupported), which the plain run requires to PASS,
# so the two runs together cover every MUST requirement. The TCK receiver listens on the host, so the connectors
# container reaches it as host.docker.internal.
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
set -a; . ./tck/pin.env; [ -f .env ] && . ./.env; set +a
TCK_DIR="${TCK_DIR:-${TMPDIR:-/tmp}/camunda-a2a-3-tck}"
export A2A_PUSH_ENABLED=true
# The endpoint starts the scripted TCK fixture instead of the agent, and deploy.sh deploys it.
export A2A_AGENT_PROCESS=a2a-tck-fixture A2A_EXTRA_RESOURCES=tck/fixture
COMPOSE=(docker compose -p camunda-a2a-3 -f blueprint/docker-compose.yml --env-file .env)
"${COMPOSE[@]}" up -d --wait connectors >/dev/null
scripts/deploy.sh
mkdir -p reports; rm -rf "$TCK_DIR/reports" reports/push
(cd "$TCK_DIR" && . .venv/bin/activate && python -I run_tck.py --sut-host "http://localhost:${PROXY_PORT:-28090}" \
    --transport jsonrpc --level must -- --webhook-host=host.docker.internal >"$ROOT/reports/push.log" 2>&1)
mkdir -p reports/push && cp -R "$TCK_DIR/reports/." reports/push/
python3 -I - reports/push <<'PY'
import json, sys
per = json.load(open(sys.argv[1] + "/compatibility.json"))["per_requirement"]
for rid, v in sorted(per.items()):
    if rid.startswith("PUSH-") or rid.startswith("CORE-CAP-001"):
        print("%-18s %s" % (rid, v["transports"].get("jsonrpc", v["status"])), (v["errors"] or [""])[0][:100])
PY
status=0
python3 -I tck/check_results.py reports/push --push --rest "http://localhost:${CAMUNDA_REST_PORT:-28080}" | tee reports/results-push.txt || status=1
python3 -I - "$ROOT" "$TCK_SHA" <<'PY'
import datetime, sys
root, sha = sys.argv[1:3]
line = [l.strip() for l in open(root + "/reports/results-push.txt") if l.startswith("RESULT")][0]
kv = dict(p.split("=") for p in line.split()[1:])
open(root + "/tck/RESULTS-push.md", "w").write("\n".join([
    "# TCK results with push notifications on", "",
    "Generated by `tck/run-push.sh` on %s." % datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC"), "",
    "- TCK: https://github.com/a2aproject/a2a-tck at `%s`, with the same fix PRs as `tck/RESULTS.md`" % sha,
    "- Command: `run_tck.py --transport jsonrpc --level must -- --webhook-host=host.docker.internal`, judged by "
    "`tck/check_results.py --push`: every PUSH-* requirement must PASS; CORE-CAP-001 is skipped by the TCK because "
    "the capability is declared", "",
    "| Executed | Skipped | Failures | Errors | MUST pass | MUST allowlisted | Incidents | Verdict |",
    "|----------|---------|----------|--------|-----------|------------------|-----------|---------|",
    "| %s | %s | %s | %s | %s | %s | %s | %s |" % (kv["executed"], kv["skipped"], kv["failures"], kv["errors"],
        kv["must_pass"], kv["must_allowlisted"], kv["incidents"], kv["verdict"]), ""]))
PY
export A2A_PUSH_ENABLED=false
"${COMPOSE[@]}" up -d --wait connectors >/dev/null
scripts/deploy.sh >/dev/null
echo "push switched off again"
exit $status
